<script setup lang="ts">
import { Plus } from '@lucide/vue';
import { ref } from 'vue';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import SchemaChangeDialog from '@/components/schema/SchemaChangeDialog.vue';
import type { ColumnInfo } from '@/types';

const props = defineProps<{
    database: string;
    table: string;
    columns: ColumnInfo[];
    otherTables: string[];
}>();

const actions = ['RESTRICT', 'CASCADE', 'SET NULL', 'NO ACTION'];

const name = ref('');
const columns = ref('');
const referencedTable = ref('');
const referencedColumns = ref('id');
const onDelete = ref('RESTRICT');
const onUpdate = ref('RESTRICT');

function reset(): void {
    name.value = '';
    columns.value = '';
    referencedTable.value = props.otherTables[0] ?? '';
    referencedColumns.value = 'id';
    onDelete.value = 'RESTRICT';
    onUpdate.value = 'RESTRICT';
}

const list = (value: string) =>
    value
        .split(',')
        .map((item) => item.trim())
        .filter((item) => item !== '');

function buildChange() {
    return {
        type: 'add_foreign_key',
        name: name.value || null,
        columns: list(columns.value),
        referencedTable: referencedTable.value,
        referencedColumns: list(referencedColumns.value),
        onDelete: onDelete.value,
        onUpdate: onUpdate.value,
    };
}

const inputClass =
    'h-8 rounded-md border border-input bg-transparent px-2 text-sm shadow-xs dark:bg-input/30';
</script>

<template>
    <SchemaChangeDialog
        :database="database"
        :table="props.table"
        title="Add foreign key"
        description="Columns on both sides must have matching types. MySQL explains any mismatch."
        :build-change="buildChange"
        trigger-label="Add foreign key"
        :trigger-icon="Plus"
        @opened="reset"
    >
        <div class="grid gap-3 sm:grid-cols-2">
            <div class="grid gap-1.5">
                <Label for="fk-columns">Columns (comma-separated)</Label>
                <Input
                    id="fk-columns"
                    v-model="columns"
                    class="h-8 font-mono"
                    list="fk-column-options"
                    placeholder="customer_id"
                />
                <datalist id="fk-column-options">
                    <option
                        v-for="column in props.columns"
                        :key="column.name"
                        :value="column.name"
                    />
                </datalist>
            </div>
            <div class="grid gap-1.5">
                <Label for="fk-name">Name (optional)</Label>
                <Input
                    id="fk-name"
                    v-model="name"
                    class="h-8 font-mono"
                    maxlength="64"
                    placeholder="Generated by MySQL"
                />
            </div>
            <div class="grid gap-1.5">
                <Label for="fk-table">References table</Label>
                <select
                    id="fk-table"
                    v-model="referencedTable"
                    :class="inputClass"
                >
                    <option v-for="other in otherTables" :key="other">
                        {{ other }}
                    </option>
                </select>
            </div>
            <div class="grid gap-1.5">
                <Label for="fk-ref-columns">Referenced columns</Label>
                <Input
                    id="fk-ref-columns"
                    v-model="referencedColumns"
                    class="h-8 font-mono"
                />
            </div>
            <div class="grid gap-1.5">
                <Label for="fk-on-delete">On delete</Label>
                <select
                    id="fk-on-delete"
                    v-model="onDelete"
                    :class="inputClass"
                >
                    <option v-for="action in actions" :key="action">
                        {{ action }}
                    </option>
                </select>
            </div>
            <div class="grid gap-1.5">
                <Label for="fk-on-update">On update</Label>
                <select
                    id="fk-on-update"
                    v-model="onUpdate"
                    :class="inputClass"
                >
                    <option v-for="action in actions" :key="action">
                        {{ action }}
                    </option>
                </select>
            </div>
        </div>
    </SchemaChangeDialog>
</template>
