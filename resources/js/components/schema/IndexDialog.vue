<script setup lang="ts">
import { Plus } from '@lucide/vue';
import { ref } from 'vue';
import { Input } from '@/components/ui/input';
import { Label } from '@/components/ui/label';
import SchemaChangeDialog from '@/components/schema/SchemaChangeDialog.vue';
import type { ColumnInfo } from '@/types';

const props = defineProps<{
    database: string;
    table: string;
    columns: ColumnInfo[];
}>();

const indexType = ref('index');
const name = ref('');
/** Selected columns, in the order they were picked (index column order matters). */
const selected = ref<string[]>([]);

function reset(): void {
    indexType.value = 'index';
    name.value = '';
    selected.value = [];
}

function toggle(column: string): void {
    selected.value = selected.value.includes(column)
        ? selected.value.filter((current) => current !== column)
        : [...selected.value, column];
}

function buildChange() {
    return {
        type: 'add_index',
        indexType: indexType.value,
        name: indexType.value === 'primary' ? null : name.value || null,
        columns: selected.value,
    };
}

const inputClass =
    'h-8 rounded-md border border-input bg-transparent px-2 text-sm shadow-xs dark:bg-input/30';
</script>

<template>
    <SchemaChangeDialog
        :database="database"
        :table="props.table"
        title="Add index"
        description="Pick columns in the order the index should use them."
        :build-change="buildChange"
        trigger-label="Add index"
        :trigger-icon="Plus"
        @opened="reset"
    >
        <div class="grid gap-3 sm:grid-cols-2">
            <div class="grid gap-1.5">
                <Label for="index-type">Type</Label>
                <select id="index-type" v-model="indexType" :class="inputClass">
                    <option value="index">Index</option>
                    <option value="unique">Unique</option>
                    <option value="fulltext">Fulltext</option>
                    <option value="primary">Primary key</option>
                </select>
            </div>
            <div v-if="indexType !== 'primary'" class="grid gap-1.5">
                <Label for="index-name">Name (optional)</Label>
                <Input
                    id="index-name"
                    v-model="name"
                    class="h-8 font-mono"
                    maxlength="64"
                    placeholder="Generated by MySQL"
                />
            </div>
        </div>
        <div class="grid gap-1.5">
            <Label>Columns</Label>
            <div class="flex flex-wrap gap-2">
                <button
                    v-for="column in columns"
                    :key="column.name"
                    type="button"
                    class="rounded-md border px-2 py-0.5 font-mono text-xs"
                    :class="
                        selected.includes(column.name)
                            ? 'border-primary bg-primary text-primary-foreground'
                            : 'hover:bg-muted'
                    "
                    @click="toggle(column.name)"
                >
                    <template v-if="selected.includes(column.name)"
                        >{{ selected.indexOf(column.name) + 1 }}.
                    </template>
                    {{ column.name }}
                </button>
            </div>
        </div>
    </SchemaChangeDialog>
</template>
